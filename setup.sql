CREATE TABLE IF NOT EXISTS public.president_transfers (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 from_user uuid NOT NULL REFERENCES public.profiles(id),
 to_user uuid NOT NULL REFERENCES public.profiles(id)
);
CREATE TABLE IF NOT EXISTS public.schedules (
 user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 schedule_date date NOT NULL,slot integer NOT NULL CHECK(slot BETWEEN 1 AND 8),
 available boolean NOT NULL DEFAULT false,PRIMARY KEY(user_id,schedule_date,slot)
);
