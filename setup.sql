   LEFT JOIN public.od_staff_role_settings s ON s.role_id=(r->>'id')::bigint
   WHERE m->>'user_id'=p.id::text AND coalesce(m->'role_ids','[]') @> jsonb_build_array((r->>'id')::bigint)
